import { describe, it, expect, beforeEach, afterEach } from "bun:test";
import { CliApp, CphPiCli, parseCliArgs, getHelpText, runCli } from "../../src/cli.ts";
import { ChatHubClient } from "../../src/transport/chathub-client.ts";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

describe("CLI --timeout Arguments & System Integration (Task 3)", () => {
  let tmpDir: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "cph-timeout-cli-test-"));
  });

  afterEach(() => {
    try {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    } catch {
      // Ignore cleanup error
    }
  });

  describe("1. parseArgs for --timeout and -t flags", () => {
    it("should parse --timeout <seconds> correctly", () => {
      const app = new CliApp({ workspaceRoot: tmpDir });
      const parsed1 = (app as any).parseArgs(["--timeout", "300"]);
      expect(parsed1.timeoutSec).toBe(300);

      const parsedEq = (app as any).parseArgs(["--timeout=180"]);
      expect(parsedEq.timeoutSec).toBe(180);
    });

    it("should parse -t <seconds> correctly when given a numeric value", () => {
      const app = new CliApp({ workspaceRoot: tmpDir });
      const parsed = (app as any).parseArgs(["-t", "450"]);
      expect(parsed.timeoutSec).toBe(450);

      const parsedStatic = (CliApp as any).parseArgs(["-t", "120"]);
      expect(parsedStatic.timeoutSec).toBe(120);
    });

    it("should still parse -t <string> as task prompt for backward compatibility", () => {
      const parsed = (CliApp as any).parseArgs(["-t", "analyze memory leak"]);
      expect(parsed.task).toBe("analyze memory leak");
      expect(parsed.timeoutSec).toBeUndefined();
    });
  });

  describe("2. CliApp forwards timeoutMs to Orchestrator and ChatHubClient", () => {
    it("should default timeoutSec to 600 (timeoutMs to 600,000) when not specified", () => {
      const app = new CliApp({ workspaceRoot: tmpDir });
      expect((app as any).timeoutSec).toBe(600);
      expect((app as any).getTimeoutSec()).toBe(600);
      expect((app as any).getTimeoutMs()).toBe(600_000);

      const orchestrator = app.getOrchestrator();
      expect((orchestrator as any).timeoutMs).toBe(600_000);

      // Verify ChatHubClient generated by createChatClient has 600,000ms
      const dummyToken = {
        id: "test",
        email: "test@example.com",
        authCookie: "dummy",
        substrateToken: "dummy",
        token: "dummy",
        expiresAt: Date.now() + 3600000,
      };
      const client = (app as any).createChatClient(dummyToken);
      expect((client as any).options.timeoutMs).toBe(600_000);
    });

    it("should forward custom timeoutSec to Orchestrator and ChatHubClient", () => {
      const app = new CliApp({
        workspaceRoot: tmpDir,
        timeoutSec: 300,
      });
      expect((app as any).timeoutSec).toBe(300);
      expect((app as any).getTimeoutSec()).toBe(300);
      expect((app as any).getTimeoutMs()).toBe(300_000);

      const orchestrator = app.getOrchestrator();
      expect((orchestrator as any).timeoutMs).toBe(300_000);

      const dummyToken = {
        id: "test",
        email: "test@example.com",
        authCookie: "dummy",
        substrateToken: "dummy",
        token: "dummy",
        expiresAt: Date.now() + 3600000,
      };
      const client = (app as any).createChatClient(dummyToken);
      expect((client as any).options.timeoutMs).toBe(300_000);
    });
  });

  describe("3. Help documentation for --timeout", () => {
    it("should include --timeout documentation in getHelpText", () => {
      const help = getHelpText();
      expect(help).toContain("--timeout");
      expect(help).toContain("-t, --timeout <seconds>");
    });

    it("should return --timeout in runCli with --help flag", async () => {
      const res = await runCli(["--help"]);
      expect(res.exitCode).toBe(0);
      expect(res.mode).toBe("help");
      expect(res.output).toContain("--timeout");
      expect(res.output).toContain("600");
    });
  });
});
